export const FALLBACK_TEXT = 'No generated response is available. You can return home whenever you choose.'
const exerciseLabels = { paced_breathing: 'Paced Breathing', stop: 'STOP', grounding_54321: '5-4-3-2-1 Grounding' }
const feedbackLabels = { helpful: 'Helpful', not_helpful: 'Not Helpful' }

export function feedbackMessage(exercise, feedback) {
  if (!exerciseLabels[exercise] || !feedbackLabels[feedback]) throw new Error('Unsupported button context')
  return `I selected ${feedbackLabels[feedback]} after the ${exerciseLabels[exercise]} exercise.`
}

// One controller per completed session; it never changes exercise state. Repeated
// choices share a request/promise. New choices/Skip/Home invalidate stale display.
export function createFeedbackResponder({ api, sessionId, exerciseType, localDate, newId = () => crypto.randomUUID(), onState }) {
  const exchanges = new Map()
  let revision = 0
  let controller = null
  const fallback = () => ({ status: 'fallback', text: FALLBACK_TEXT, label: 'Static fallback · not generated by a model' })
  return {
    async select(feedback, ready = Promise.resolve(true)) {
      const request = ++revision
      if (feedback === 'skipped') {
        controller?.abort()
        onState({ status: 'idle', text: '', label: '' })
        return
      }
      onState({ status: 'loading', text: '', label: 'Preparing a brief response…' })
      const saved = await ready
      if (request !== revision) return
      if (!saved) { onState(fallback()); return }
      let promise = exchanges.get(feedback)
      if (!promise) {
        controller = new AbortController()
        promise = Promise.resolve().then(() => api.feedbackResponse({
          request_id: newId(), session_id: sessionId, exercise_type: exerciseType,
          feedback, user_message: feedbackMessage(exerciseType, feedback),
          ...(localDate ? { local_date: localDate() } : {}),
        }, controller.signal))
        exchanges.set(feedback, promise)
      }
      try {
        const result = await promise
        if (request !== revision) return
        if (result.session_id !== sessionId || result.feedback !== feedback) throw new Error('Context mismatch')
        const assistant = result.messages?.find(message => message.role === 'assistant' && message.ordinal === 2)
        if (result.status === 'succeeded' && result.saved === true && ['mock','live'].includes(result.provider_mode)
            && typeof assistant?.content === 'string' && assistant.content.length <= 240) {
          onState({ status: 'ready', text: assistant.content, label: result.provider_mode === 'mock' ? 'Demo response · mock provider' : 'Model response' })
        } else if (result.status === 'pending') {
          onState({ status: 'fallback', text: 'The response is still pending. You can return home whenever you choose.', label: 'Static notice · not generated by a model' })
        } else onState(fallback())
      } catch {
        if (request === revision) onState(fallback())
      }
    },
    cancel() {
      revision++
      controller?.abort()
    },
  }
}
