import { test } from 'node:test'
import assert from 'node:assert/strict'
import { createFeedbackResponder, feedbackMessage, FALLBACK_TEXT } from '../src/feedbackResponse.js'

function result(feedback='helpful', mode='mock') {
  return {status:'succeeded',saved:true,provider_mode:mode,session_id:'fictional-session',feedback,
    messages:[{role:'user',ordinal:1,content:feedbackMessage('stop',feedback)},
              {role:'assistant',ordinal:2,content:'Feedback noted. You can return home whenever you choose.'}]}
}
function create(api) {
  const states=[]
  const responder=createFeedbackResponder({api,sessionId:'fictional-session',exerciseType:'stop',newId:()=> 'fictional-request',onState:state=>states.push(state)})
  return {states,responder}
}

test('Helpful and Not Helpful submit only fixed button context and label mock vs live', async () => {
  const requests=[]
  const {states,responder}=create({feedbackResponse:async body=>{requests.push(body);return result(body.feedback,body.feedback==='helpful'?'mock':'live')}})
  await responder.select('helpful');assert.equal(states.at(-1).label,'Demo response · mock provider')
  await responder.select('not_helpful');assert.equal(states.at(-1).label,'Model response')
  assert.equal(requests.length,2)
  assert.deepEqual(Object.keys(requests[0]).sort(),['exercise_type','feedback','request_id','session_id','user_message'])
  assert.equal(requests[0].user_message,'I selected Helpful after the STOP exercise.')
  assert.throws(()=>feedbackMessage('stop','skipped'))
})
test('Skip is immediate, clears response, and never invokes provider API', async () => {
  let calls=0
  const {states,responder}=create({feedbackResponse:async()=>{calls++;return result()}})
  await responder.select('skipped')
  assert.equal(calls,0);assert.equal(states.at(-1).status,'idle')
})
test('duplicate pending or completed clicks share one exchange request', async () => {
  let release,calls=0
  const {states,responder}=create({feedbackResponse:()=>{calls++;return new Promise(resolve=>{release=resolve})}})
  const a=responder.select('helpful'),b=responder.select('helpful')
  for(let i=0;i<5;i++)await Promise.resolve()
  assert.equal(calls,1);assert.equal(states.at(-1).status,'loading')
  release(result());await Promise.all([a,b])
  await responder.select('helpful');assert.equal(calls,1);assert.equal(states.at(-1).status,'ready')
})
test('Skip and Home/cancel ignore late responses and abort pending fetch', async () => {
  let release,signal
  const {states,responder}=create({feedbackResponse:(_,s)=>{signal=s;return new Promise(resolve=>{release=resolve})}})
  const pending=responder.select('helpful')
  for(let i=0;i<5;i++)await Promise.resolve()
  await responder.select('skipped');assert.equal(signal.aborted,true)
  release(result());await pending;assert.equal(states.at(-1).status,'idle')
  const other=create({feedbackResponse:async()=>result()})
  let ready
  const beforeSave=other.responder.select('helpful',new Promise(resolve=>{ready=resolve}))
  other.responder.cancel();ready(true);await beforeSave
  assert.equal(other.states.at(-1).status,'loading') // No late response was displayed.
})
test('failed save, timeout/error, invalid response, and backend unavailability use explicit static fallback', async () => {
  let calls=0
  const unsaved=create({feedbackResponse:async()=>{calls++;return result()}})
  await unsaved.responder.select('helpful',Promise.resolve(false));assert.equal(calls,0)
  assert.equal(unsaved.states.at(-1).text,FALLBACK_TEXT)
  for(const response of [()=>{throw Error('network')},async()=>({status:'failed',session_id:'fictional-session',feedback:'helpful',messages:[]}),async()=>({...result(),session_id:'wrong-session'}),async()=>({...result(),messages:[]})]) {
    const {states,responder}=create({feedbackResponse:response})
    await responder.select('helpful')
    assert.equal(states.at(-1).status,'fallback');assert.match(states.at(-1).label,/not generated by a model/)
  }
})
test('latest feedback wins the visible response even when an older request finishes later', async () => {
  const release={}
  const {states,responder}=create({feedbackResponse:body=>new Promise(resolve=>{release[body.feedback]=resolve})})
  const a=responder.select('helpful');for(let i=0;i<5;i++)await Promise.resolve()
  const b=responder.select('not_helpful');for(let i=0;i<5;i++)await Promise.resolve()
  release.not_helpful(result('not_helpful'));await b
  const latest=states.at(-1)
  release.helpful(result());await a
  assert.equal(states.at(-1),latest)
})

